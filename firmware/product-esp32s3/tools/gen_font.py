#!/usr/bin/env python3
"""Extracts glyph outlines from Liberation Sans Bold into lib/mnui/mn_font_data.cpp.

The firmware draws text by filling these outlines with the same anti-aliased rasteriser it uses for shapes, so any size
works from one small table (about 30 KB) and no bitmap-per-size data is needed.

Characters: ASCII 32..126, plus code 0x7F = middle dot and 0x80 = ellipsis (the phone only ever sends printable ASCII, so
those two codes are free for the firmware's own use). Kerning comes from the font's 'kern' table.

Licence: Liberation Fonts are SIL Open Font License 1.1 (copyright 2010 Google Corporation, 2012 Red Hat, Inc.). The
generated table is a derivative of that font and stays under the OFL; see lib/mnui/OFL.txt. Do not name it "Liberation".

    pip install fonttools
    python3 tools/gen_font.py [path/to/LiberationSans-Bold.ttf]
"""
import os
import sys

from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "lib", "mnui", "mn_font_data.cpp")
DEFAULT = "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"

CODES = list(range(32, 127)) + [0x7F, 0x80]
UNICODE = {c: c for c in range(32, 127)}
UNICODE[0x7F] = 0x00B7
UNICODE[0x80] = 0x2026


def main() -> None:
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    f = TTFont(src)
    cmap = f.getBestCmap()
    glyf, hmtx = f["glyf"], f["hmtx"]
    names = {}
    pts, on, ends, recs = [], [], [], []
    for code in CODES:
        name = cmap[UNICODE[code]]
        names[code] = name
        g = glyf[name]
        adv = hmtx[name][0]
        p0, c0 = len(pts), len(ends)
        if g.numberOfContours != 0:
            coords, end_pts, flags = g.getCoordinates(glyf)
            for (x, y), fl in zip(coords, flags):
                pts.append((int(x), int(y)))
                on.append(1 if fl & 1 else 0)
            ends.extend(e + 1 for e in end_pts)              # exclusive end, relative to this glyph's first point
        recs.append((adv, p0, len(pts) - p0, c0, len(ends) - c0))
    # kerning between the characters we have
    kern = []
    if "kern" in f:
        table = f["kern"].kernTables[0].kernTable
        for a in CODES:
            for b in CODES:
                v = table.get((names[a], names[b]))
                if v:
                    kern.append((a, b, int(v)))
    kern.sort()
    with open(OUT, "w") as o:
        o.write("// GENERATED by tools/gen_font.py from Liberation Sans Bold (SIL Open Font License 1.1, see OFL.txt). Do not edit.\n")
        o.write('#include "mn_font.h"\n\nnamespace mnui {\nnamespace fontdata {\n\n')
        o.write(f"const int kUnitsPerEm = {f['head'].unitsPerEm};\nconst int kAscent = {f['hhea'].ascent};\n"
                f"const int kDescent = {-f['hhea'].descent};\nconst int kFirst = 32;\nconst int kCount = {len(CODES)};\n\n")
        o.write(f"const int16_t kPts[{len(pts) * 2}] = {{\n")
        flat = [str(v) for xy in pts for v in xy]
        for i in range(0, len(flat), 16):
            o.write("  " + ",".join(flat[i:i + 16]) + ",\n")
        o.write("};\n\n")
        o.write(f"const uint8_t kOn[{len(on)}] = {{\n")
        for i in range(0, len(on), 40):
            o.write("  " + ",".join(str(v) for v in on[i:i + 40]) + ",\n")
        o.write("};\n\n")
        o.write(f"const uint16_t kEnds[{len(ends)}] = {{\n")
        for i in range(0, len(ends), 16):
            o.write("  " + ",".join(str(v) for v in ends[i:i + 16]) + ",\n")
        o.write("};\n\n")
        o.write(f"const GlyphRec kGlyphs[{len(recs)}] = {{\n")
        for r in recs:
            o.write("  {%d,%d,%d,%d,%d},\n" % r)
        o.write("};\n\n")
        o.write(f"const int kKernCount = {len(kern)};\nconst KernRec kKern[{max(1, len(kern))}] = {{\n")
        for a, b, v in kern:
            o.write("  {%d,%d,%d},\n" % (a, b, v))
        if not kern:
            o.write("  {0,0,0},\n")
        o.write("};\n\n}  // namespace fontdata\n}  // namespace mnui\n")
    print(f"wrote {os.path.relpath(OUT)}: {len(CODES)} glyphs, {len(pts)} points, {len(ends)} contours, {len(kern)} kern pairs")


if __name__ == "__main__":
    main()
